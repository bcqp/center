"""Render assets/data.js from the JSON files in data/. Run after any change to data/."""
import json, datetime, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
def load(n): return json.loads((ROOT / "content" / n).read_text(encoding="utf-8"))
def main():
    payload = {"updated": datetime.date.today().isoformat(), "series": load("series.json"),
               "briefs": load("briefs.json"), "topics": load("topics.json")}
    out = "/* BCQP Policy Briefs: site data. Generated by tools/build_data.py from data/*.json */\nwindow.BCQP = " + \
          json.dumps(payload, indent=2, ensure_ascii=False) + ";\n"
    (ROOT / "assets" / "data.js").write_text(out, encoding="utf-8")
    base = "https://bcqp.github.io/center/"
    pub = sorted([b for b in payload["briefs"] if b.get("status") == "published"], key=lambda b: b["date"], reverse=True)[:6]
    feed = [{"title": b["title"], "date": b["date"], "topic": b["topic"], "summary": b["summary"], "url": base + "briefs/" + b["slug"] + ".html",
             "image": base + "briefs/" + b["slug"] + "/fig1_stylised_facts.png"} for b in pub]
    (ROOT / "feed.json").write_text(json.dumps({"updated": payload["updated"], "briefs": feed}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("assets/data.js written:", len(payload["series"]), "series,", len(payload["briefs"]), "briefs")
if __name__ == "__main__": main()
